import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('./',import.meta.url);
const p=JSON.parse(await readFile(new URL('profile.json',root),'utf8'));
for(const a of p.assets){
 const bytes=await readFile(new URL(a.file,root));
 if(createHash('sha256').update(bytes).digest('hex')!==a.sha256)throw new Error('Brand asset changed: '+a.file);
}
function luminance(hex){
 const h=hex.slice(1);const values=(h.length===3?h.split('').map(c=>c+c).join(''):h).match(/../g).map(v=>parseInt(v,16)/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4);
 return values.reduce((sum,v,i)=>sum+v*[.2126,.7152,.0722][i],0);
}
for(const mode of ['light','dark']){
 const t={...p.tokens.light,...(mode==='dark'?p.tokens.dark:{})};
 for(const [a,b] of [[t['--dt-gray'],t['--dt-page']],[t['--dt-gray'],t['--surface-card']],[t['--dt-blue'],t['--surface-card']],['#ffffff',t['--dt-blue-fill']]]){
  const values=[luminance(a),luminance(b)].sort((a,b)=>a-b);
  if((values[1]+.05)/(values[0]+.05)<4.5)throw new Error('Insufficient '+mode+' contrast: '+a+' / '+b);
 }
}
const vars=o=>Object.entries(o).map(([k,v])=>k+':'+v+';').join('');
const native='--wf-color-primary:var(--dt-blue-fill);--wf-color-on-primary:#ffffff;--wf-color-background:var(--dt-page);--wf-color-surface:var(--surface-card);--wf-color-text:var(--dt-gray);--wf-color-muted:var(--dt-gray);--wf-color-border:var(--dt-line);--wf-color-accent:var(--dt-blue);--wf-color-danger:var(--danger);--wf-color-success:var(--success);';
const light=':root{color-scheme:light;'+vars(p.tokens.light)+'}:root:root{'+native+'}';
const dark=vars(p.tokens.dark)+'color-scheme:dark;';
await writeFile(new URL('brand.css',root),'/* Generated by brand/build.mjs from profile.json. */\n'+light+'\n:root[data-theme="dark"]{'+dark+'}\n@media(prefers-color-scheme:dark){:root:not([data-theme="light"]):not([data-theme="dark"]){'+dark+'}}\n');
console.log('Brand verified: '+p.assets.length+' assets; '+p.version);

const hex=v=>v.length===4?'#'+v.slice(1).split('').map(c=>c+c).join(''):v;
const t=p.tokens.light;
const logo=name=>p.assets.find(a=>a.file.endsWith('/'+name)).url;
const surface={background:hex(t['--dt-page']),text:hex(t['--dt-gray']),muted:hex(t['--dt-gray']),border:hex(t['--dt-line']),link:hex(t['--dt-blue']),hover:hex(t['--dt-hover']),focus:hex(t['--dt-blue'])};
const theme={themeVersion:2,brand:{name:p.client,logoUrl:logo('deltron-logo-horizontal.svg'),logoAlt:p.client,faviconUrl:'',logoLightUrl:logo('deltron-logo-horizontal.svg'),logoDarkUrl:logo('deltron-logo-horizontal-white.svg')},colors:{primary:hex(t['--dt-blue-fill']),secondary:hex(t['--dt-gray']),accent:hex(t['--dt-blue']),background:hex(t['--dt-page']),surface:hex(t['--dt-surface']),text:hex(t['--dt-gray']),muted:hex(t['--dt-gray']),border:hex(t['--dt-line']),danger:hex(t['--red-500']),success:hex(t['--green-500'])},typography:p.engineDefaults.typography,layout:p.engineDefaults.layout,surfaces:{header:surface,footer:surface}};
await writeFile(new URL('theme.json',root),JSON.stringify(theme,null,2)+'\n');
