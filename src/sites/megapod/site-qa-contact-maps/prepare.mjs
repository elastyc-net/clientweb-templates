import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const [baselinePath, outputPath] = process.argv.slice(2);
if (!baselinePath || !outputPath) throw new Error('Usage: node prepare.mjs <scoped-baseline.json> <writes.json>');
const baseline = JSON.parse(fs.readFileSync(baselinePath, 'utf8'));
const item = baseline.items.find(i => i.itemType === 'page' && i.itemKey === 'tree-kontakt');
const referenceItem = baseline.items.find(i => i.itemType === 'page' && i.itemKey === 'tree-reference');
if (!item || !referenceItem || baseline.items.length !== 2) throw new Error('Expected only current Contact and Reference definitions.');
const definition = structuredClone(item.definition);
const code = definition.regions.main.find(i => i.instanceKey === 'tree-kontakt-content').customCode;
if (code.js.trim()) throw new Error('Review existing Contact JavaScript before applying.');
const esc = value => value.replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const decode = value => value.replaceAll('&amp;', '&').replaceAll('&quot;', '"');
let count = 0;
const mapPanels = [];
code.html = code.html.replace(/<article class="mp-location">[\s\S]*?<\/article>/g, card => {
  const name = decode(card.match(/<h3>([^<]+)<\/h3>/)[1]);
  const address = decode(card.match(/<address>([^<]+)<\/address>/)[1]);
  const map = card.match(/<a class="mp-btn" href="(https:\/\/www\.google\.com\/maps\/search\/[^\"]+)">Kako do nas<span aria-hidden="true">↗<\/span><\/a>/);
  const oldDetails = card.match(/<details class="mp-map">[\s\S]*?<\/details>/);
  if (!map || !oldDetails) throw new Error('Unexpected map structure for ' + name);
  const src = decode(oldDetails[0].match(/<iframe[^>]+src="([^"]+)"/)[1]);
  const destination = new URL(decode(map[1])).searchParams.get('query');
  if (!destination) throw new Error('Missing location destination.');
  const directions = new URL('https://www.google.com/maps/dir/');
  directions.searchParams.set('api', '1');
  directions.searchParams.set('destination', destination);
  directions.searchParams.set('dir_action', 'navigate');
  mapPanels.push(`<div data-mp-map-panel="${count}" hidden><iframe title="Mapa — ${esc(name)}" src="${esc(src)}" loading="lazy" referrerpolicy="no-referrer-when-downgrade" allowfullscreen></iframe></div>`);
  const button = `<button class="mp-btn" type="button" aria-haspopup="dialog" aria-controls="mp-location-dialog" aria-label="Mapa i dolazak — ${esc(name)}" data-mp-open-map data-mp-map-index="${count}" data-mp-map-name="${esc(name)}" data-mp-map-address="${esc(address)}" data-mp-map-directions="${esc(directions.href)}">Mapa i dolazak<span aria-hidden="true">↗</span></button>`;
  count++;
  return card.replace(map[0], button).replace(oldDetails[0], '');
});
if (count !== 4) throw new Error('Expected exactly four location cards.');
const dialog = `<dialog class="mp-location-dialog" id="mp-location-dialog" aria-labelledby="mp-map-title" aria-describedby="mp-map-address"><div class="mp-location-dialog-head"><div><h2 id="mp-map-title" data-mp-map-title>Mapa lokacije</h2><p class="mp-location-dialog-address" id="mp-map-address" data-mp-map-address></p></div><button class="mp-location-dialog-close" type="button" data-mp-close-map aria-label="Zatvorite mapu" autofocus>×</button></div>${mapPanels.join('')}<div class="mp-location-dialog-footer"><p>Planirajte dolazak do izabrane lokacije.</p><a class="mp-btn" href="https://www.google.com/maps/" target="_blank" rel="noopener noreferrer" data-mp-map-directions>Pokrenite navigaciju<span aria-hidden="true">↗</span></a></div></dialog>`;
if (!code.html.endsWith('</div></div>')) throw new Error('Unexpected Contact container.');
code.html = code.html.slice(0, -12) + dialog + '</div></div>';
code.css += '\n' + fs.readFileSync(path.join(here, 'contact.css'), 'utf8');
code.js = fs.readFileSync(path.join(here, 'maps.js'), 'utf8');
fs.writeFileSync(path.join(here, 'kontakt.json'), JSON.stringify(definition, null, 2) + '\n');
const reference = structuredClone(referenceItem.definition);
reference.regions.main.find(i => i.instanceKey === 'tree-reference-content').customCode.css += '\n' + fs.readFileSync(path.join(here, 'reference.css'), 'utf8');
const writes = [{itemType: item.itemType, itemKey: item.itemKey, expectedRevision: item.draftRevision, definition}, {itemType: referenceItem.itemType, itemKey: referenceItem.itemKey, expectedRevision: referenceItem.draftRevision, definition: reference}];
fs.writeFileSync(outputPath, JSON.stringify({siteKey: baseline.siteKey, expectedSnapshotHash: baseline.snapshotHash, writes}, null, 2) + '\n');
console.log('Prepared Contact map dialog and touch-friendly Reference filters.');
